export type TranslationKey = keyof typeof translations.pt;

interface I18nContextValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: TranslationKey) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Locale | null;
      return saved && ['pt', 'en', 'fr'].includes(saved) ? saved : 'pt';
    } catch { return 'pt'; }
  });

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale === 'pt' ? 'pt-CV' : locale === 'en' ? 'en' : 'fr';
  }, [locale]);

  function setLocale(l: Locale) { setLocaleState(l); }

  function t(key: TranslationKey): string {
    return (translations[locale] as Record<string, string>)[key]
      ?? (translations.pt as Record<string, string>)[key]
      ?? key;
  }

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
